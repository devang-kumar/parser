import mongoose from 'mongoose';

const UserSchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
  },
  email: {
    type: String,
    required: true,
    unique: true,
  },
  password: {
    type: String,
    required: true,
  },
  role: {
    type: String,
    enum: ['user', 'admin'],
    default: 'user',
  },
  status: {
    type: String,
    enum: ['active', 'blocked'],
    default: 'active',
  },
  avatarColor: {
    type: String,
    default: 'bg-indigo-600',
  },
  lastLogin: {
    type: Date,
  },
}, { timestamps: true });

export default mongoose.model('User', UserSchema);
